import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const projectRoot = process.cwd();
const baselineRoot = path.join(projectRoot, "reports", "baseline");
const summaryPath = path.join(baselineRoot, "SUMMARY.md");

async function findJsonFiles(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = [];

  for (const entry of entries) {
    const fullPath = path.join(directory, entry.name);
    if (entry.isDirectory()) {
      files.push(...(await findJsonFiles(fullPath)));
    } else if (entry.name.endsWith(".json")) {
      files.push(fullPath);
    }
  }

  return files;
}

function formatBytes(bytes) {
  if (!Number.isFinite(bytes)) {
    return "unknown";
  }

  if (bytes >= 1024 ** 2) {
    return `${(bytes / 1024 ** 2).toFixed(2)} MiB`;
  }

  if (bytes >= 1024) {
    return `${(bytes / 1024).toFixed(1)} KiB`;
  }

  return `${bytes} B`;
}

function formatCount(count) {
  return count === 0 ? "0 (none)" : String(count);
}

const files = await findJsonFiles(baselineRoot);
const baselineReports = [];
const measurements = new Map();

for (const filePath of files) {
  const value = JSON.parse(await readFile(filePath, "utf8"));
  const relativePath = path.relative(baselineRoot, filePath);

  if (relativePath.startsWith(`measurements${path.sep}`)) {
    measurements.set(relativePath, value);
  } else if (Array.isArray(value.items)) {
    baselineReports.push({ relativePath, value });
  }
}

baselineReports.sort((left, right) =>
  left.relativePath.localeCompare(right.relativePath),
);

const lines = [
  "# Baseline Defects",
  "",
  "This file is generated by `npm run baseline:summary`.",
  "",
  "Items in this report are known baseline defects. The automated suite compares",
  "against the corresponding JSON files and fails only when a new finding appears.",
  "",
  "## Defect counts",
  "",
  "| Baseline | Findings |",
  "| --- | ---: |",
];

for (const report of baselineReports) {
  lines.push(
    `| \`${report.relativePath.replaceAll("\\", "/")}\` | ${formatCount(report.value.items.length)} |`,
  );
}

lines.push("", "## Known findings", "");

for (const report of baselineReports) {
  lines.push(
    `### ${report.relativePath.replaceAll("\\", "/")}`,
    "",
    `Recorded findings: ${formatCount(report.value.items.length)}`,
    "",
  );

  if (report.value.items.length === 0) {
    lines.push("No findings were recorded.", "");
    continue;
  }

  for (const item of report.value.items) {
    lines.push(`- ${item}`, "");
  }
}

const linkMeasurement = measurements.get(
  path.join("measurements", "internal-links.json"),
);
const htmlMeasurement = measurements.get(
  path.join("measurements", "html-validation.json"),
);

lines.push("## Measurements", "");

if (linkMeasurement) {
  lines.push(
    `- Public pages checked: ${linkMeasurement.publicPageCount}`,
    `- DOM references checked: ${linkMeasurement.checkedDomReferenceCount}`,
    `- CSS targets checked: ${linkMeasurement.checkedCssTargetCount}`,
    `- Missing targets: ${formatCount(linkMeasurement.missingTargetCount)}`,
    `- Placeholder links: ${formatCount(linkMeasurement.placeholderLinkCount)}`,
    "",
  );
}

if (htmlMeasurement) {
  lines.push(
    `- HTML pages checked: ${htmlMeasurement.pagesChecked}`,
    `- HTML errors: ${formatCount(htmlMeasurement.errorCount)}`,
    `- HTML warnings: ${formatCount(htmlMeasurement.warningCount)}`,
    "",
    "### HTML validation rules",
    "",
    "| Rule | Findings |",
    "| --- | ---: |",
  );

  for (const [ruleId, count] of Object.entries(htmlMeasurement.ruleCounts ?? {})) {
    lines.push(`| \`${ruleId}\` | ${count} |`);
  }

  lines.push("");
}

const pageWeightEntries = [...measurements.entries()]
  .filter(([relativePath]) =>
    relativePath.startsWith(`measurements${path.sep}page-weights${path.sep}`),
  )
  .map(([, value]) => value)
  .sort((left, right) => right.totalBytes - left.totalBytes);

if (pageWeightEntries.length > 0) {
  lines.push(
    "### Page resource weights",
    "",
    "These values are same-origin browser resources measured while each page loads.",
    "They are uncompressed development-server sizes, not production transfer sizes.",
    "",
    "| Page | Resources | Measured bytes |",
    "| --- | ---: | ---: |",
  );

  for (const page of pageWeightEntries) {
    lines.push(
      `| ${page.page.label} | ${page.resourceCount} | ${formatBytes(page.totalBytes)} |`,
    );
  }

  lines.push("");
}

await writeFile(summaryPath, `${lines.join("\n").trimEnd()}\n`, "utf8");
console.log(`Baseline summary written to ${path.relative(projectRoot, summaryPath)}`);
